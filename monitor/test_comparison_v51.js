const fs=require('fs'),vm=require('vm'),assert=require('assert');
const html=fs.readFileSync('index.html','utf8');
const start=html.indexOf('function v48Check(');
const end=html.indexOf('function legacyCompareView(){',start);
assert(start>0&&end>start,'V48-V50 functions missing');
const source=html.slice(start,end);
const feed=JSON.parse(fs.readFileSync('data/official_previews.json','utf8')).campaigns;
const gates=JSON.parse(fs.readFileSync('data/provisional_rule_gates.json','utf8'));
const rules=Array.isArray(gates)?gates:(gates.rules||gates.campaigns||[]);
assert.equal(feed.length,18);assert.equal(rules.length,18);
const context={scenario:{date:'2026-10-15',category:'Market',amount:3000},v48Answers:{},V48_RULES:rules, V48_LABELS:{},officialPreviews:feed,CARDS:[],S:{selected:[]},esc:x=>String(x),officialLink:()=>'',console};
vm.createContext(context);vm.runInContext(source,context);
let n=0;function check(name,fn){fn();n++;console.log('PASS',name)}
const market=feed.find(c=>c.category==='Market');assert(market,'market campaign');
const r=rules.find(x=>x.campaign_id===market.id);assert(r,'market rule');
check('unknown when no evidence',()=>assert.equal(context.v48Check(market).state,'unknown'));
context.v48Answers[market.id]={[r.required_evidence[0]]:false};
check('negative condition excludes',()=>assert.equal(context.v48Check(market).state,'ineligible'));
context.v48Answers[market.id]=Object.fromEntries(r.required_evidence.map(f=>[f,true]));
check('all declared conditions still only potential',()=>assert.equal(context.v48Check(market).state,'potential'));
context.scenario.date='2026-09-30';
check('outside date is ineligible',()=>assert.equal(context.v48Check(market).state,'ineligible'));
context.scenario.date='2026-10-15';
const card={bank:market.bank,family:(market.eligibleFamilies||[])[0]||'Test',product:'Test',id:'test'};
check('bank mismatch excluded',()=>assert.equal(context.v50Rows([{...card,bank:'Different'}],[market],'2026-10-15','Market')[0].items.length,0));
check('category mismatch excluded',()=>assert.equal(context.v50Rows([card],[market],'2026-10-15','Other')[0].items.length,0));
check('date before campaign excluded',()=>assert.equal(context.v50Rows([card],[market],'2026-09-30','Market')[0].items.length,0));
check('date after campaign excluded',()=>assert.equal(context.v50Rows([card],[market],'2026-11-01','Market')[0].items.length,0));
check('date boundaries included',()=>{assert.equal(context.v50Rows([card],[market],market.start,'Market')[0].items.length,1);assert.equal(context.v50Rows([card],[market],market.end,'Market')[0].items.length,1)});
check('counts reflect provisional state',()=>assert.equal(context.v50Rows([card],[market],'2026-10-15','Market')[0].counts.potential,1));
check('selected absent category is not widened to all',()=>{context.scenario.category='No matching category';context.CARDS=[card];context.S.selected=['test'];const output=context.compareRealView();assert(!output.includes(market.title));assert(output.includes('No matching category'))});
check('no selected cards asks for card selection',()=>{context.S.selected=[];assert(context.compareRealView().includes('Önce kartlarını seç'))});
check('comparison never claims definite TL earnings',()=>{context.S.selected=['test'];context.scenario.category='Market';assert(context.compareRealView().includes('Kazanç hesaplanmıyor'))});
console.log(`SUCCESS: ${n} integration-oriented logic tests`);
